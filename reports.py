"""PDF report builders (ReportLab). All numbers come from the trained run / live data."""
from __future__ import annotations

import io
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (Paragraph, SimpleDocTemplate, Spacer, Table,
                               TableStyle)

NAVY = colors.HexColor("#0b1c2c")
GREEN = colors.HexColor("#0f9d76")
GREY = colors.HexColor("#5b6b7c")
LINE = colors.HexColor("#d8e0e7")


def _styles():
    ss = getSampleStyleSheet()
    ss.add(ParagraphStyle("H", parent=ss["Title"], fontSize=17, textColor=NAVY,
                          spaceAfter=2, alignment=0))
    ss.add(ParagraphStyle("Sub", parent=ss["Normal"], fontSize=9, textColor=GREY,
                          spaceAfter=14))
    ss.add(ParagraphStyle("H2s", parent=ss["Heading2"], fontSize=11.5, textColor=NAVY,
                          spaceBefore=12, spaceAfter=6))
    ss.add(ParagraphStyle("Body2", parent=ss["Normal"], fontSize=9, leading=13,
                          textColor=colors.HexColor("#233240")))
    return ss


def _table(rows, widths=None, header=True):
    t = Table(rows, colWidths=widths, hAlign="LEFT")
    style = [("FONTSIZE", (0, 0), (-1, -1), 8.6),
             ("TEXTCOLOR", (0, 0), (-1, -1), colors.HexColor("#233240")),
             ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
             ("TOPPADDING", (0, 0), (-1, -1), 5),
             ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE)]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef4f2")),
                  ("TEXTCOLOR", (0, 0), (-1, 0), NAVY),
                  ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold")]
    t.setStyle(TableStyle(style))
    return t


def _build(title, subtitle, story):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=16 * mm, bottomMargin=16 * mm,
                            title=title, author="Smart Grid Analytics")
    ss = _styles()
    story = [Paragraph(title, ss["H"]), Paragraph(subtitle, ss["Sub"])] + story
    story.append(Spacer(1, 10))
    story.append(Paragraph(
        "Generated by the Smart Grid Energy Consumption Forecasting & Analysis platform. "
        "Machine learning: Linear Regression, Decision Tree and Random Forest on a "
        "chronological train/test split.", ss["Body2"]))
    doc.build(story)
    buf.seek(0)
    return buf


def _response(buf, filename):
    from fastapi.responses import Response
    return Response(content=buf.getvalue(), media_type="application/pdf",
                    headers={"Content-Disposition": f'attachment; filename="{filename}"'})


def comparison_pdf(run, dataset_name):
    ss = _styles()
    story = [Paragraph("Model comparison", ss["H2s"])]
    rows = [["Model", "MAE (kWh)", "RMSE (kWh)", "R²", "MAPE (%)"]]
    for m in ("Linear Regression", "Decision Tree", "Random Forest"):
        mm = run["metrics"][m]
        star = "  ★ best" if m == run["best_model"] else ""
        rows.append([m + star, f"{mm['MAE']:.3f}", f"{mm['RMSE']:.3f}",
                     f"{mm['R2']:.4f}", f"{mm['MAPE']:.2f}" if mm["MAPE"] is not None else "—"])
    story.append(_table(rows))
    story.append(Paragraph("Evaluation setup", ss["H2s"]))
    story.append(_table([
        ["Dataset", dataset_name],
        ["Granularity", run["grain"]],
        ["Train rows", str(run["train_rows"])],
        ["Test rows", str(run["test_rows"])],
        ["Train period", f"{run['train_period']['start']} → {run['train_period']['end']}"],
        ["Test period", f"{run['test_period']['start']} → {run['test_period']['end']}"],
        ["Split", run["split_note"]],
        ["Best model", run["best_model"]],
        ["Trained at", run["trained_at"]],
    ], header=False))
    story.append(Paragraph("Feature importance (Random Forest)", ss["H2s"]))
    fi = run["feature_importance"]["Random Forest"][:10]
    story.append(_table([["Feature", "Importance"]] +
                        [[f["feature"], f"{f['importance'] * 100:.2f}%"] for f in fi]))
    return _response(_build("Model comparison report",
                            f"{dataset_name} · generated {datetime.utcnow():%Y-%m-%d %H:%M} UTC",
                            story), "model_comparison.pdf")


def forecast_pdf(fc, dataset_name, metrics):
    ss = _styles()
    story = [Paragraph("Forecast summary", ss["H2s"])]
    s = fc["summary"]
    story.append(_table([
        ["Model", fc["model"]],
        ["Forecast interval", fc["interval"]],
        ["Granularity", fc["grain"]],
        ["Points forecast", str(s["horizon_points"])],
        ["Total predicted (kWh)", f"{s['total_predicted_kwh']:,.2f}"],
        ["Average predicted (kWh)", f"{s['average_predicted_kwh']:,.2f}"],
        ["Peak period", f"{s['peak']['label']} · {s['peak']['predicted_kwh']:,.2f} kWh"],
        ["Lowest period", f"{s['lowest']['label']} · {s['lowest']['predicted_kwh']:,.2f} kWh"],
        ["Change vs recent average", f"{s['change_vs_recent_pct']:+.2f}%"],
        ["Test MAE / RMSE / R²",
         f"{metrics['MAE']:.3f} / {metrics['RMSE']:.3f} / {metrics['R2']:.4f}"],
    ], header=False))
    story.append(Paragraph("Predictions", ss["H2s"]))
    rows = [["Period", "Predicted kWh"]]
    for p in fc["points"][:60]:
        rows.append([p["label"], f"{p['predicted_kwh']:,.2f}"])
    if len(fc["points"]) > 60:
        rows.append(["…", f"{len(fc['points']) - 60} more rows in the CSV export"])
    story.append(_table(rows))
    story.append(Paragraph(fc["method"], ss["Body2"]))
    return _response(_build("Forecast report",
                            f"{dataset_name} · {fc['model']} · "
                            f"{datetime.utcnow():%Y-%m-%d %H:%M} UTC", story),
                     "forecast_report.pdf")


def historical_pdf(agg, dataset_name):
    ss = _styles()
    s = agg["summary"]
    story = [Paragraph(f"{agg['interval'].capitalize()} analysis", ss["H2s"])]
    story.append(_table([
        ["Source grain", agg["grain"]],
        ["Period", f"{s['period']['start']} → {s['period']['end']}"],
        ["Buckets", str(s["buckets"])],
        ["Total (kWh)", f"{s['total_kwh']:,.2f}"],
        ["Average per bucket (kWh)", f"{s['average_kwh']:,.2f}"],
        ["Peak bucket", f"{s['peak']['label']} · {s['peak']['total_kwh']:,.2f} kWh"],
        ["Lowest bucket", f"{s['lowest']['label']} · {s['lowest']['total_kwh']:,.2f} kWh"],
    ], header=False))
    story.append(Paragraph("Buckets", ss["H2s"]))
    rows = [["Period", "Total kWh", "Average kWh", "Records"]]
    for b in agg["buckets"][:80]:
        rows.append([b["label"], f"{b['total_kwh']:,.2f}", f"{b['avg_kwh']:,.2f}",
                     str(b["records"])])
    story.append(_table(rows))
    return _response(_build("Historical analysis report",
                            f"{dataset_name} · {datetime.utcnow():%Y-%m-%d %H:%M} UTC", story),
                     f"historical_{agg['interval']}.pdf")


def dataset_pdf(preview, dataset_name):
    ss = _styles()
    d = preview["dataset"]
    story = [Paragraph("Dataset profile", ss["H2s"])]
    story.append(_table([
        ["File", d["filename"]],
        ["Rows", str(d["rows"])],
        ["Columns", str(d["columns"])],
        ["Timestamp column", str(preview["selected"]["timestamp_column"])],
        ["Consumption column", str(preview["selected"]["consumption_column"])],
        ["Date range", f"{preview['date_range']['start']} → {preview['date_range']['end']}"
         if preview["date_range"] else "not detected"],
        ["Missing cells", str(preview["total_missing_cells"])],
        ["Duplicate rows", str(preview["duplicate_rows"])],
    ], header=False))
    story.append(Paragraph("Columns and types", ss["H2s"]))
    story.append(_table([["Column", "dtype"]] +
                        [[c, t] for c, t in preview["dtypes"].items()]))
    return _response(_build("Dataset analysis report",
                            f"{dataset_name} · {datetime.utcnow():%Y-%m-%d %H:%M} UTC", story),
                     "dataset_report.pdf")


def live_pdf(rows):
    ss = _styles()
    story = [Paragraph("Live smart meter readings", ss["H2s"]),
             Paragraph(f"{len(rows)} stored readings (SQLite).", ss["Body2"]), Spacer(1, 6)]
    table = [["Meter", "kWh", "Timestamp (UTC)", "Status", "Source"]]
    for r in rows[:120]:
        table.append([r["meter_id"], f"{r['energy_consumption']:,.3f}", r["timestamp"],
                      r["status"], r["source"]])
    story.append(_table(table))
    return _response(_build("Live readings report",
                            f"generated {datetime.utcnow():%Y-%m-%d %H:%M} UTC", story),
                     "live_readings.pdf")
